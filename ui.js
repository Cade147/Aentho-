// ── Toast Notifications ───────────────────────────────────────────
function toast(message, type = 'info', duration = 3500) {
  const container = document.getElementById('toast-container');
  if (!container) return;

  const icons = { success: '✓', error: '✕', warning: '⚠', info: 'ℹ' };
  const el = document.createElement('div');
  el.className = `toast ${type}`;
  el.innerHTML = `<span style="font-weight:700">${icons[type] || 'ℹ'}</span> ${message}`;
  container.appendChild(el);

  setTimeout(() => {
    el.classList.add('hide');
    el.addEventListener('animationend', () => el.remove());
  }, duration);
}

// ── Confirm Dialog ────────────────────────────────────────────────
function confirm_(message, title = 'Confirm', danger = false) {
  return new Promise((resolve) => {
    const overlay = document.getElementById('confirm-overlay');
    const titleEl = document.getElementById('confirm-title');
    const msgEl   = document.getElementById('confirm-message');
    const okBtn   = document.getElementById('confirm-ok');
    const cancelBtn = document.getElementById('confirm-cancel');

    if (!overlay) { resolve(window.confirm(message)); return; }

    titleEl.textContent = title;
    msgEl.textContent   = message;
    okBtn.className     = `btn ${danger ? 'btn-danger' : 'btn-primary'}`;
    okBtn.textContent   = danger ? 'Delete' : 'Confirm';

    overlay.classList.add('active');

    const ok = () => { cleanup(); resolve(true); };
    const cancel = () => { cleanup(); resolve(false); };

    function cleanup() {
      overlay.classList.remove('active');
      okBtn.removeEventListener('click', ok);
      cancelBtn.removeEventListener('click', cancel);
    }

    okBtn.addEventListener('click', ok);
    cancelBtn.addEventListener('click', cancel);
  });
}

// ── Modal Helpers ─────────────────────────────────────────────────
function openModal(id) {
  document.getElementById(id)?.classList.add('active');
  document.body.style.overflow = 'hidden';
}

function closeModal(id) {
  document.getElementById(id)?.classList.remove('active');
  document.body.style.overflow = '';
}

// Close modal on overlay click
document.addEventListener('click', (e) => {
  if (e.target.classList.contains('modal-overlay')) {
    e.target.classList.remove('active');
    document.body.style.overflow = '';
  }
});

// ── Currency Formatter ────────────────────────────────────────────
function formatCurrency(amount, currency = 'ZAR') {
  const n = parseFloat(amount) || 0;
  // Use Intl if supported
  try {
    return new Intl.NumberFormat('en-ZA', { style: 'currency', currency, minimumFractionDigits: 2 }).format(n);
  } catch {
    return `R ${n.toFixed(2)}`;
  }
}

// ── Number formatter ──────────────────────────────────────────────
function formatNumber(n) {
  if (n >= 1_000_000) return (n / 1_000_000).toFixed(1) + 'M';
  if (n >= 1_000)     return (n / 1_000).toFixed(1) + 'K';
  return n.toString();
}

// ── Date Formatter ────────────────────────────────────────────────
function formatDate(iso, short = false) {
  const d = new Date(iso);
  if (isNaN(d)) return '—';
  return short
    ? d.toLocaleDateString('en-ZA', { day: '2-digit', month: 'short' })
    : d.toLocaleDateString('en-ZA', { day: '2-digit', month: 'short', year: 'numeric' });
}

function formatDateTime(iso) {
  const d = new Date(iso);
  if (isNaN(d)) return '—';
  return d.toLocaleString('en-ZA', {
    day: '2-digit', month: 'short', year: 'numeric',
    hour: '2-digit', minute: '2-digit'
  });
}

function timeAgo(iso) {
  const diff = Date.now() - new Date(iso).getTime();
  const mins = Math.floor(diff / 60000);
  if (mins < 1)   return 'just now';
  if (mins < 60)  return `${mins}m ago`;
  const hrs = Math.floor(mins / 60);
  if (hrs  < 24)  return `${hrs}h ago`;
  const days = Math.floor(hrs / 24);
  return `${days}d ago`;
}

// ── Avatar initials ───────────────────────────────────────────────
function initials(name = '') {
  return name.split(' ').map(w => w[0]).join('').slice(0, 2).toUpperCase() || '?';
}

// ── Percentage change ─────────────────────────────────────────────
function pctChange(current, previous) {
  if (!previous) return { value: 0, dir: 'neutral' };
  const pct = ((current - previous) / Math.abs(previous)) * 100;
  return {
    value: Math.abs(pct).toFixed(1),
    dir: pct > 0 ? 'up' : pct < 0 ? 'down' : 'neutral'
  };
}

